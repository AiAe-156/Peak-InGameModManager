"""Collects MCE inline UI text into the built-in term catalogue.

Loc.T(en, zhCn, zhTw) is self-sufficient at runtime, but only catalogue terms (AllInlineTerms) are written into the
built-in language layer and exported for translators. This script:

  1. scans src/ for three-argument T(...)/F(...)/Loc.T(...)/Loc.F(...) calls with literal arguments;
  2. scans two-argument T(en, zh) calls (their local helper passes zh as zh-tw) and two-argument helpers with a
     third optional argument;
  3. writes every English text that is not yet a catalogue key into src/Loc.Release23Terms.cs, with zh-tw taken from
     the three-argument call, or from TW_OVERRIDES / the review table for two-argument calls.

Two-argument calls without a reviewed zh-tw are listed in pending_zhtw.tsv (en, zh-cn, suggested zh-tw) and are NOT
written until the suggestion is reviewed (copy the TSV row into tw_reviewed.tsv). Run with --check to only report.
"""
import os, re, sys, csv
sys.stdout.reconfigure(encoding='utf-8')
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
SRC = os.path.join(ROOT, 'src')
OUT = os.path.join(SRC, 'Loc.Release23Terms.cs')
REVIEWED = os.path.join(HERE, 'tw_reviewed.tsv')
PENDING = os.path.join(HERE, 'pending_zhtw.tsv')
CHECK = '--check' in sys.argv

STR = r'"((?:[^"\\]|\\.)*)"'
term_re = re.compile(r'new\(\s*' + STR + r'\s*,\s*' + STR + r'\s*,\s*' + STR + r'\s*,\s*' + STR + r'\s*\)')
three = re.compile(r'(?<![\w.])(?:Loc\.)?(?:T|F|L)\(\s*' + STR + r'\s*,\s*' + STR + r'\s*,\s*' + STR)
two = re.compile(r'(?<![\w.])(?:T|L)\(\s*' + STR + r'\s*,\s*' + STR + r'\s*\)')

def catalogue(skip_generated):
    keys = set()
    for f in os.listdir(SRC):
        if not (f.startswith('Loc') and f.endswith('.cs')): continue
        if skip_generated and f == os.path.basename(OUT): continue
        for m in term_re.finditer(open(os.path.join(SRC, f), encoding='utf-8').read()):
            keys.add(m.group(1).strip()); keys.add(m.group(2).strip())
    return keys

def sources():
    for d, _, fs in os.walk(SRC):
        if os.sep + 'bin' in d or os.sep + 'obj' in d: continue
        for f in fs:
            if f.endswith('.cs') and not f.startswith('Loc'):
                p = os.path.join(d, f)
                yield os.path.relpath(p, ROOT), open(p, encoding='utf-8').read().splitlines()

def unescape(s): return s.replace('\\"', '"')

reviewed = {}
if os.path.exists(REVIEWED):
    with open(REVIEWED, encoding='utf-8', newline='') as fh:
        for row in csv.reader(fh, delimiter='\t'):
            if len(row) >= 3 and row[0] and not row[0].startswith('#'): reviewed[row[0]] = row[2]

existing = catalogue(skip_generated=not CHECK)
entries = {}      # english -> (zhCn, zhTw, origin)
pending = {}      # english -> zhCn
for rel, lines in sources():
    for n, line in enumerate(lines, 1):
        for m in three.finditer(line):
            en, zc, zt = m.group(1), m.group(2), m.group(3)
            if en.strip() in existing or en.strip() == '': continue
            entries.setdefault(en, (zc, zt, f'{rel}:{n}'))
        for m in two.finditer(line):
            en, zc = m.group(1), m.group(2)
            if en.strip() in existing or en in entries or en.strip() == '': continue
            if en in reviewed: entries[en] = (zc, reviewed[en], f'{rel}:{n}')
            else: pending.setdefault(en, (zc, f'{rel}:{n}'))

print(f'existing catalogue keys: {len(existing)}')
print(f'new terms to write: {len(entries)}  (three-arg + reviewed two-arg)')
print(f'two-arg terms still needing a reviewed zh-tw: {len(pending)}')
if CHECK:
    sys.exit(1 if entries or pending else 0)

with open(PENDING, 'w', encoding='utf-8', newline='') as fh:
    w = csv.writer(fh, delimiter='\t')
    w.writerow(['# english', 'zh-cn', 'zh-tw (fill in, then copy the row to tw_reviewed.tsv)', 'first use'])
    for en, (zc, origin) in sorted(pending.items()): w.writerow([en, zc, '', origin])

def esc(s): return s  # already C#-escaped as captured from source
body = ['// Generated by 验证/发布前审查/collect_terms.py — catalogue entries for inline text added after 2.1.',
        '// Keys are the original English. Regenerate instead of editing by hand; reviewed zh-tw for two-argument',
        '// calls comes from 验证/发布前审查/tw_reviewed.tsv.',
        'namespace ModConfigEnhance;', '', 'internal static partial class Loc', '{',
        '    private static readonly Term[] Release23Terms =', '    {']
for en, (zc, zt, origin) in sorted(entries.items(), key=lambda kv: kv[1][2]):
    body.append(f'        new("{esc(en)}", "{esc(en)}", "{esc(zc)}", "{esc(zt)}"),')
body += ['    };', '}', '']
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(body))
print('wrote', os.path.relpath(OUT, ROOT), 'and', os.path.relpath(PENDING, ROOT))
