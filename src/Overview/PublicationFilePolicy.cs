#nullable enable
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.RegularExpressions;

namespace ModConfigEnhance.Overview;

// Automatic installation-file collection only. Validated author-profile resources
// are copied separately so a referenced screenshot or video is retained.
internal static class PublicationFilePolicy
{
    internal static bool StartupAttachment(string relative)
    {
        string path = relative.Replace('\\', '/');
        return path.StartsWith("BepInEx/patchers/", StringComparison.OrdinalIgnoreCase)
            || path.StartsWith("BepInEx/monomod/", StringComparison.OrdinalIgnoreCase);
    }

    internal static bool ExcludedStartupAttachment(string relative, IEnumerable<string> excluded)
    {
        string path = relative.Replace('\\', '/');
        if (!StartupAttachment(path)) return false;
        return excluded.Any(item => {
            string root = item.Replace('\\', '/').TrimEnd('/');
            return path.Equals(root, StringComparison.OrdinalIgnoreCase)
                || path.StartsWith(root + "/", StringComparison.OrdinalIgnoreCase);
        });
    }

    internal static bool ProfileConfigPath(string relative)
    {
        string path = relative.Replace('\\', '/');
        string file = Path.GetFileName(path);
        return path.Length > 0 && !Path.IsPathRooted(path) && !path.Contains(':')
            && !path.Split('/').Any(p => p == ".." || p.Length == 0)
            && !ModConfigEnhance.Updating.ManagerIdentity.IsManagerConfigFile(file)
            && !file.Equals("AutoTranslatorConfig.ini", StringComparison.OrdinalIgnoreCase)
            && !path.StartsWith("Translation/", StringComparison.OrdinalIgnoreCase)
            && path.IndexOf("/_AutoGeneratedTranslations", StringComparison.OrdinalIgnoreCase) < 0
            && !ModConfigEnhance.Updating.ManagerIdentity.IsConfigDirectory(path.Split('/')[0])
            && !ModConfigEnhance.Updating.ManagerIdentity.UnderRuntime(path)
            && !path.StartsWith("XUnity", StringComparison.OrdinalIgnoreCase);
    }
    private static readonly HashSet<string> ExcludedFolders = new(StringComparer.OrdinalIgnoreCase)
        { "cache", "logs", "log", "backup", "backups", "备份", "验证", "exports", "export", "obj", "bin", ".git", ".vs", ".trash" };
    private static readonly string[] ExcludedExtensions = { ".log", ".bak", ".tmp", ".partial", ".lastvalid", ".pdb", ".zip", ".7z", ".rar", ".pending" };
    private static readonly Regex CaptureName = new(@"^(?:PixPin|Snipaste|Screenshot|ScreenRecording|截图|录屏)[ _-]", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

    internal static bool Keep(string relative)
    {
        string[] parts = relative.Replace('\\', '/').Split('/');
        // This exact installation-level path is private runtime state. A plugin
        // package named MCE below plugins remains ordinary publishable content.
        if (parts.Length >= 2 && parts[0].Equals("BepInEx", StringComparison.OrdinalIgnoreCase) && ModConfigEnhance.Updating.ManagerIdentity.IsRuntimeDirectory(parts[1])) return false;
        if (parts.Any(p => ExcludedFolders.Contains(p) || p.StartsWith("待安装", StringComparison.OrdinalIgnoreCase) || ModConfigEnhance.Updating.ManagerIdentity.IsPackFolder(p))) return false;
        string name = parts[parts.Length - 1];
        if (name.Equals("HowManyTimesWeClimbedTogether.json", StringComparison.OrdinalIgnoreCase)) return false;
        if (ModConfigEnhance.Updating.PluginFileNames.IsAssembly(name)) return true;
        if (ModConfigEnhance.Updating.PluginFileNames.IsUpdateArtifact(name)) return false;
        if (ExcludedExtensions.Any(e => name.EndsWith(e, StringComparison.OrdinalIgnoreCase))) return false;
        if (Regex.IsMatch(name, @"\.bak[_.-]|\.before-", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant)) return false;
        // .dll.old also represents a disabled plugin and is projected to the
        // profile's enabled/disabled filename by the publisher.
        if (name.EndsWith(".old", StringComparison.OrdinalIgnoreCase) && !name.EndsWith(".dll.old", StringComparison.OrdinalIgnoreCase)) return false;
        return !CaptureName.IsMatch(name);
    }

    internal static bool IsUpdaterRuntime(string file, string bepinexDirectory)
    {
        string full = Path.GetFullPath(file).TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
        foreach (string name in new[] { ModConfigEnhance.Updating.ManagerIdentity.RuntimeDirectory, ModConfigEnhance.Updating.ManagerIdentity.LegacyRuntimeDirectory })
        {
            string root = Path.GetFullPath(Path.Combine(bepinexDirectory, name)).TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
            if (full.Equals(root, StringComparison.OrdinalIgnoreCase) || full.StartsWith(root + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase)) return true;
        }
        return false;
    }

    internal static bool IsSelfDemo(string file, string selfDirectory)
    {
        string prefix = Path.GetFullPath(Path.Combine(selfDirectory, "Demo")).TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar;
        return Path.GetFullPath(file).StartsWith(prefix, StringComparison.OrdinalIgnoreCase);
    }

    internal static bool KeepSelfCopy(string file, string selfGuid, IEnumerable<(string Guid, string Root, bool Loaded)> packages)
    {
        var active = packages.FirstOrDefault(m => m.Guid.Equals(selfGuid, StringComparison.OrdinalIgnoreCase) && m.Loaded);
        if (active.Root == null) return true;
        return !packages.Any(m => m.Guid.Equals(selfGuid, StringComparison.OrdinalIgnoreCase) && !m.Loaded
            && !m.Root.Equals(active.Root, StringComparison.OrdinalIgnoreCase)
            && !packages.Any(other => other.Root.Equals(m.Root, StringComparison.OrdinalIgnoreCase) && !other.Guid.Equals(selfGuid, StringComparison.OrdinalIgnoreCase))
            && Path.GetFullPath(file).StartsWith(Path.GetFullPath(m.Root).TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase));
    }
}
